async def test_two_caption_files_first_listed_is_primary_and_the_other_is_kept():
    # SYNTHETIC: the real page above lists one caption file. This adds a
    # second <track> line (same shape as the real one) to exercise the
    # two-file rule. A real two-file video (one Pointe-Claire video has de
    # and fr, per the 2026-10-07 live check) was not captured.
    html = load_fixture("webtv_coop", "video_with_captions.html").replace(
        "</video-js>",
        f'<track src="/webPlayerSubtitles/subtitleFile/key/{KEY}/filename/en_subtitles.vtt"'
        ' srclang="en" kind="captions" label="English" /></video-js>',
    )
    en_url = VTT_URL.replace("fr_subtitles", "en_subtitles")
    routes = _with_captions_routes(CHANNEL_VIDEO_URL)
    routes[CHANNEL_VIDEO_URL] = FakeResponse(
        status=200, text=html, url=CHANNEL_VIDEO_URL
    )
    routes[en_url] = FakeResponse(
        status=200,
        text="WEBVTT - generated by WEBTV.COOP\n\n1\n00:00:01.000 --> 00:00:03.000\nGood evening, everyone.\n",
        url=en_url,
    )
    with mock_session(routes):
        result = await WebtvCoopAssetFinder().resolve(CHANNEL_VIDEO_URL)

    assert result.transcript_language == "fr"
    assert len(result.segments) == 60
    assert [a.language for a in result.alternate_transcripts] == ["en"]
    assert result.alternate_transcripts[0].segments[0].text == "Good evening, everyone."


