def _with_captions_routes(url):
    return {
        url: FakeResponse(
            status=200,
            text=load_fixture("webtv_coop", "video_with_captions.html"),
            url=url,
        ),
        VTT_URL: FakeResponse(
            status=200,
            text=load_fixture(
                "webtv_coop", "captions_pointe_claire_2026-10-06_first60.vtt"
            ),
            url=VTT_URL,
        ),
    }


@pytest.mark.parametrize("url", [CHANNEL_VIDEO_URL, SITE_VIDEO_URL])
async def test_resolve_video_with_captions_both_address_shapes(url):
    with mock_session(_with_captions_routes(url)):
        result = await WebtvCoopAssetFinder().resolve(url)

    assert result.platform == "webtv_coop"
    assert result.external_id == f"webtv_coop:{KEY}"
    assert result.title == "2026-10-06 Conseil de la Ville de Pointe-Claire"
    assert result.date == "2026-10-06"
    assert result.video_format == "m3u8"
    assert result.video_url == (
        "https://5976193b91256.streamlock.net/vod/"
        f"smil:{KEY}_1791337581.smil/playlist.m3u8?1791411162"
    )
    assert result.video_duration_seconds == 7405.0
    # Only the channel address names its channel. The site-wide page does
    # not (its /channel/ links are site navigation), so no hint is sent.
    assert result.video_channel == ("webtv_coop:4" if "/channel/" in url else None)
    assert result.transcript_language == "fr"
    assert len(result.segments) == 60
    assert result.segments[0].text.startswith("Bonsoir")
    assert result.alternate_transcripts == []
    assert result.transcript_warnings == []


