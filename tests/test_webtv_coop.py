def test_pins_resolve_a_channel_to_its_government():
    from app.utils.gov_registry.resolver import page_hints_for, resolve_government

    # Pointe-Claire, channel 4 -> ca:csd:2466097 (tenant_overrides.csv). The
    # site-wide address carries no channel, so the pin fires from the
    # adapter's video_channel hint; the channel address fires by its number.
    for path, channel in (
        (f"/video/x/{KEY}", "webtv_coop:4"),
        (f"/channel/video/x/{KEY}/4", None),
    ):
        match = resolve_government(
            None,
            tenant_host="webtv.coop",
            path=path,
            page_hints=page_hints_for("webtv_coop", f"webtv_coop:{KEY}", channel),
        )
        assert match.gov_id == "ca:csd:2466097"
        assert match.tier == "pinned"


