def test_site_wide_page_title_and_nav_links_are_not_read_as_the_channel():
    # A trimmed shape of the real site-wide page captured 2026-10-07 from
    # https://webtv.coop/video/2026-04-07-reconstruction-complte-de-lavenue-
    # chestnut/f767a2b8607a6fb4de4adad22becc003 : a different <h1> class,
    # a "- Média - WEBTV.COOP" title, and site-navigation links to channels
    # 12 and 13 (neither is this video's channel).
    html = (
        "<title>2026-04-07 - Reconstruction complète de l’avenue Chestnut - Média - WEBTV.COOP\n</title>"
        '<a class="channelLink" href="/channel/Production-ISCA/12">x</a>'
        '<a class="channelLink" href="/channel/La-coop-WEBTV/13">x</a>'
    )
    assert WebtvCoopAssetFinder._title(html) == (
        "2026-04-07 - Reconstruction complète de l’avenue Chestnut"
    )
    html += '<h1 class="no-indent media-title">2026-04-07 - Titre</h1>'
    assert WebtvCoopAssetFinder._title(html) == "2026-04-07 - Titre"
