def test_address_helpers_and_tenant_key():
    assert media_key_from_url(CHANNEL_VIDEO_URL) == KEY
    assert media_key_from_url(SITE_VIDEO_URL) == KEY
    assert media_key_from_url("https://webtv.coop/channel/Pointe2DClaire/4") is None
    assert channel_from_url(CHANNEL_VIDEO_URL) == "4"
