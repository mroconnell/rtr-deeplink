def test_table_lookup_recognizes_a_page_authored_abbreviation():
    # "Ft. Worth" is how real pages actually write it (user's own call,
    # 2026-08-15 -- see _STOPRULE_ABBREV_OK's comment); the Census table's
    # own key is the spelled-out "Fort Worth". Added specifically so
    # extract_jurisdiction_chain()'s validation gate (which requires a
    # candidate to actually validate before being accepted) doesn't
    # reject every abbreviated real name it was built to preserve.
    assert je._table_lookup("Ft. Worth") == ("place", ["TX"])
    assert je._table_lookup("Mt. Vernon") is not None
    assert je.finalize_jurisdiction("City of Ft. Worth").confidence == "validated"


def test_table_lookup_recognizes_a_spelled_out_saint():
    # Real bug found in the 2026-08-15 Census-baseline audit (BACKLOG.md):
    # stored "Saint Paul" used to miss the table's own key, since the
    # real Census places table stores this family abbreviated ("St. Paul
    # city", confirmed via a direct grep -- 148 real "St. " rows, zero
    # "Saint " rows), the opposite direction from "Ft. Worth"/"Mt.
    # Vernon" above, which the table stores spelled out.
    #
    # "AB" joined this list 2026-08-17 when the real Canadian data table
    # was added (BACKLOG.md's "Jurisdiction-bleed, confirmed cross-
    # platform" entry) -- St. Paul, Alberta is a real, confirmed Canadian
    # town, genuinely name-ambiguous with the 11 US states below now that
    # both live in the same table. Exactly the kind of real US/Canada
    # collision that entry predicted would "extend for free" from the
    # existing ambiguity-safety, not a bug in this fix.
    assert je._table_lookup("Saint Paul") == (
        "place",
        ["AB", "AK", "AR", "IA", "IN", "KS", "MN", "MO", "NE", "OR", "TX", "VA"],
    )
    assert je.finalize_jurisdiction("City of Saint Paul, MN").confidence == "validated"


