def test_county_and_place_zip_lookups_can_legitimately_disagree():
    # The real trap this whole module is built around: 95403's county
    # answer (Sonoma County) and place answer (Santa Rosa city) are both
    # correct, but answer different questions -- a caller must pick
    # based on which TYPE it already knows this jurisdiction to be, never
    # let the city-shaped address silently stand in for the county.
    county = je.lookup_county_by_zip("95403")
    place = je.lookup_place_by_zip("95403")
    assert county[0] != place[0]
    assert county[1] == place[1] == "CA"  # same state either way


